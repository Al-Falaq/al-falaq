#!/usr/bin/env python3
"""Generate the M4 Hijri month-start tables and pin-parity goldens.

Usage:
    python3 tools/gen_hijri.py --path /tmp/opencode/al-falak-pin

Writes, relative to the repo root:
    src/Hijri/Data/UmmAlQuraMonthStarts.php
    src/Hijri/Data/MabimsMonthStarts.php
    tests/Goldens/hijri_tabular.csv
    tests/Goldens/hijri_uqu.csv
    tests/Goldens/hijri_mabims.csv

The shipped tables ARE the pin's rule output, so UQ/MABIMS parity is exact
rather than characterized. The generator is deterministic: rerunning against
the same pin SHA reproduces byte-identical files (no clock, no set iteration
order, no locale-dependent formatting). Regeneration is a reviewable manual
gate; CI only recomputes the embedded digest.

Canonical table digest (must match the PHP constants and the PHP test):
    SHA256 = sha256("\\n".join(starts))   # ASCII LF, no trailing newline
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import subprocess
import sys
from datetime import date, timedelta
from pathlib import Path

# Supported spans (spec §4.7/§4.8). Floors are the pinned rule's own rst rows.
UQ_SPAN = (1423, 1, 1500, 12, date(2002, 3, 15))
MABIMS_SPAN = (1445, 1, 1500, 12, date(2023, 7, 19))
MABIMS_COUNTRIES = ("MY", "ID", "SG", "BN")

TABULAR_START = date(1900, 1, 1)
TABULAR_END = date(2100, 12, 31)
TABULAR_STRIDE = 97

PHP_PER_LINE = 5
PHP_INDENT = "        "


def load_pin(pin_path: Path):
    """Import the pinned package from a checkout and return its calendars."""
    sys.path.insert(0, str(pin_path / "src"))

    from alfalak.calendar.MabimsCalendar import MabimsCalendar
    from alfalak.calendar.TabularCalendar import TabularCalendar
    from alfalak.calendar.UmmAlQuraCalendar import UmmAlQuraCalendar

    return TabularCalendar, UmmAlQuraCalendar, MabimsCalendar


def month_starts(calendar, first_year: int, first_month: int, anchor: date,
                 last_year: int, last_month: int) -> list[date]:
    """Walk the pin's rule month by month; returns starts plus one sentinel."""
    starts: list[date] = []
    year, month, day = first_year, first_month, anchor

    while (year, month) <= (last_year, last_month):
        length = calendar.month_length(year, month)

        if length not in (29, 30):
            raise SystemExit(f"pin returned month length {length} for {year}-{month:02d}")

        starts.append(day)
        day = day + timedelta(days=length)
        year, month = (year + 1, 1) if month == 12 else (year, month + 1)

    starts.append(day)
    return starts


def digest(starts: list[date]) -> str:
    """Canonical digest of one table: sha256 of the LF-joined ISO starts."""
    return hashlib.sha256("\n".join(d.isoformat() for d in starts).encode("utf-8")).hexdigest()


def php_list(values: list[str], indent: str = PHP_INDENT) -> str:
    """Render a list of strings as a PHP array body, a few per line.

    `indent` must reproduce the column the caller put the first element at, or
    the continuation lines misalign and `composer cs` (@PER) rewrites the file,
    silently diverging the committed data from the generator's output.
    """
    quoted = [f"'{value}'" for value in values]
    lines = [
        ", ".join(quoted[index:index + PHP_PER_LINE])
        for index in range(0, len(quoted), PHP_PER_LINE)
    ]
    return (",\n" + indent).join(lines)


def render_uq(pin_sha: str, starts: list[date]) -> str:
    """Render the Umm al-Qura data class."""
    first_year, first_month, last_year, last_month, _ = UQ_SPAN
    return f"""<?php

declare(strict_types=1);

namespace AlFalaq\\AlFalaq\\Hijri\\Data;

/**
 * Generated Umm al-Qura month starts ({first_year}-{first_month:02d} .. {last_year}-{last_month:02d} AH) plus one sentinel.
 *
 * Encodes the pin's {first_year}H rule at Makkah: on the 29th evening the month
 * completes 29 days iff the moonset lag is positive and the moon age is below
 * 15 days at Makkah sunset; otherwise 30. Generated by
 * `python3 tools/gen_hijri.py` from pin {pin_sha}; do not edit by hand.
 *
 * @internal
 */
final class UmmAlQuraMonthStarts
{{
    /** First supported Hijri year. */
    public const FIRST_YEAR = {first_year};

    /** First supported Hijri month (Muharram). */
    public const FIRST_MONTH = {first_month};

    /** Last supported Hijri year. */
    public const LAST_YEAR = {last_year};

    /** Last supported Hijri month (Dhu al-Hijjah). */
    public const LAST_MONTH = {last_month};

    /** SHA256 of the LF-joined STARTS values (canonical digest input). */
    public const SHA256 = '{digest(starts)}';

    /** @var non-empty-list<string> Month-start Gregorian days, then one sentinel. */
    public const STARTS = [
        {php_list([d.isoformat() for d in starts])},
    ];
}}
"""


def render_mabims(pin_sha: str, tables: dict[str, list[date]]) -> str:
    """Render the per-country MABIMS data class."""
    first_year, first_month, last_year, last_month, _ = MABIMS_SPAN
    digest_constants = "\n".join(
        f"    /** SHA256 of the LF-joined STARTS_BY_COUNTRY['{code}'] values. */\n"
        f"    public const SHA256_{code} = '{digest(tables[code])}';"
        for code in MABIMS_COUNTRIES
    )
    table_entries = ",\n\n".join(
        f"""        '{code}' => [
            {php_list([d.isoformat() for d in tables[code]], PHP_INDENT + "    ")},
        ]"""
        for code in MABIMS_COUNTRIES
    )

    for_country_arms = chr(10).join(
        f"            MabimsCountry::{code} => self::STARTS_BY_COUNTRY['{code}'],"
        for code in MABIMS_COUNTRIES
    )
    digest_arms = chr(10).join(
        f"            MabimsCountry::{code} => self::SHA256_{code},"
        for code in MABIMS_COUNTRIES
    )

    return f"""<?php

declare(strict_types=1);

namespace AlFalaq\\AlFalaq\\Hijri\\Data;

use AlFalaq\\AlFalaq\\Hijri\\Enums\\MabimsCountry;

/**
 * Generated per-country MABIMS month starts ({first_year}-{first_month:02d} .. {last_year}-{last_month:02d} AH) plus one sentinel each.
 *
 * Encodes the pin's Neo-MABIMS rule (crescent altitude >= 3 deg and elongation
 * >= 6.4 deg at sunset) evaluated at each member state's national proxy point.
 * Generated by `python3 tools/gen_hijri.py` from pin {pin_sha}; do not edit by
 * hand.
 *
 * @internal
 */
final class MabimsMonthStarts
{{
    /** First supported Hijri year. */
    public const FIRST_YEAR = {first_year};

    /** First supported Hijri month (Muharram). */
    public const FIRST_MONTH = {first_month};

    /** Last supported Hijri year. */
    public const LAST_YEAR = {last_year};

    /** Last supported Hijri month (Dhu al-Hijjah). */
    public const LAST_MONTH = {last_month};

{digest_constants}

    /** @var array<string, non-empty-list<string>> Month starts per country code, then one sentinel. */
    public const STARTS_BY_COUNTRY = [
{table_entries},
    ];

    /**
     * Month-start table for one member state.
     *
     * @param MabimsCountry $country Supported member state.
     * @return non-empty-list<string> Month-start Gregorian days, then one sentinel.
     */
    public static function forCountry(MabimsCountry $country): array
    {{
        return match ($country) {{
{for_country_arms}
        }};
    }}

    /**
     * Canonical digest of one country's table.
     *
     * @param MabimsCountry $country Supported member state.
     * @return string Lowercase hex SHA256.
     */
    public static function digestFor(MabimsCountry $country): string
    {{
        return match ($country) {{
{digest_arms}
        }};
    }}
}}
"""


def write_csv(path: Path, header: list[str], rows: list[list[str]]) -> None:
    """Write a golden CSV with LF newlines."""
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(header)
        writer.writerows(rows)


def main() -> int:
    """CLI entry point."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--path", default="/tmp/opencode/al-falak-pin",
                        help="Pinned checkout path (default: /tmp/opencode/al-falak-pin)")
    parser.add_argument("--pin", default=None,
                        help="Pin SHA to embed (default: the checkout HEAD)")
    parser.add_argument("--out", default=".", help="Repo root to write into")
    args = parser.parse_args()

    pin_path = Path(args.path).resolve()
    root = Path(args.out).resolve()

    head_sha = subprocess.check_output(
        ["git", "-C", str(pin_path), "rev-parse", "HEAD"], text=True
    ).strip()
    dirty = subprocess.check_output(
        ["git", "-C", str(pin_path), "status", "--porcelain", "--untracked-files=no"],
        text=True,
    )

    if dirty:
        raise SystemExit(f"pin checkout at {pin_path} has tracked modifications; refusing to generate")

    if args.pin is not None and args.pin != head_sha:
        raise SystemExit(f"--pin {args.pin} does not match checkout HEAD {head_sha}")

    TabularCalendar, UmmAlQuraCalendar, MabimsCalendar = load_pin(pin_path)

    pin_sha = head_sha

    # --- observational tables -------------------------------------------------
    uq_first, uq_first_month, uq_last, uq_last_month, uq_anchor = UQ_SPAN
    uq_calendar = UmmAlQuraCalendar()
    uq_starts = month_starts(uq_calendar, uq_first, uq_first_month, uq_anchor, uq_last, uq_last_month)

    mabims_tables: dict[str, list[date]] = {}
    for code in MABIMS_COUNTRIES:
        calendar = MabimsCalendar(code)
        mabims_tables[code] = month_starts(
            calendar, MABIMS_SPAN[0], MABIMS_SPAN[1], MABIMS_SPAN[4], MABIMS_SPAN[2], MABIMS_SPAN[3]
        )

    data_dir = root / "src" / "Hijri" / "Data"
    data_dir.mkdir(parents=True, exist_ok=True)
    with (data_dir / "UmmAlQuraMonthStarts.php").open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(render_uq(pin_sha, uq_starts))

    with (data_dir / "MabimsMonthStarts.php").open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(render_mabims(pin_sha, mabims_tables))

    # --- goldens --------------------------------------------------------------
    goldens = root / "tests" / "Goldens"
    goldens.mkdir(parents=True, exist_ok=True)
    tag = f"pin:{pin_sha[:12]}"

    tabular_calendar = TabularCalendar()
    tabular_rows: list[list[str]] = []
    day = TABULAR_START
    index = 0

    while day <= TABULAR_END:
        if index % TABULAR_STRIDE == 0:
            hijri = tabular_calendar.from_gregorian(day)
            tabular_rows.append([day.isoformat(), hijri.isoformat(), tag])
        day += timedelta(days=1)
        index += 1

    write_csv(goldens / "hijri_tabular.csv", ["gregorian", "hijri", "source"], tabular_rows)

    uq_rows: list[list[str]] = []
    year, month = uq_first, uq_first_month
    for start in uq_starts[:-1]:
        hijri = uq_calendar.from_gregorian(start)
        expected = f"{year:04d}-{month:02d}-01"

        if hijri.isoformat() != expected:
            raise SystemExit(f"pin disagreement: uqu {start} -> {hijri.isoformat()} != {expected}")

        uq_rows.append([start.isoformat(), expected, tag])
        year, month = (year + 1, 1) if month == 12 else (year, month + 1)

    write_csv(goldens / "hijri_uqu.csv", ["gregorian", "hijri", "source"], uq_rows)

    mabims_rows: list[list[str]] = []
    for code in MABIMS_COUNTRIES:
        calendar = MabimsCalendar(code)
        year, month = MABIMS_SPAN[0], MABIMS_SPAN[1]

        for start in mabims_tables[code][:-1]:
            hijri = calendar.from_gregorian(start)
            expected = f"{year:04d}-{month:02d}-01"

            if hijri.isoformat() != expected:
                raise SystemExit(f"pin disagreement: mabims/{code} {start} -> {hijri.isoformat()} != {expected}")

            mabims_rows.append([code, start.isoformat(), expected, tag])
            year, month = (year + 1, 1) if month == 12 else (year, month + 1)

    write_csv(goldens / "hijri_mabims.csv", ["country", "gregorian", "hijri", "source"], mabims_rows)

    # --- report ---------------------------------------------------------------
    print(f"pin            {pin_sha}")
    print(f"uqu months     {len(uq_starts) - 1}  digest {digest(uq_starts)}")
    for code in MABIMS_COUNTRIES:
        print(f"mabims/{code}     {len(mabims_tables[code]) - 1} months  digest {digest(mabims_tables[code])}")
    print(f"goldens        tabular {len(tabular_rows)}  uqu {len(uq_rows)}  mabims {len(mabims_rows)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
